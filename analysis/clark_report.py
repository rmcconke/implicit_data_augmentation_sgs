"""Markdown report of the Clark baseline and Table 3 amplitude metrics.

Reads clark_results.json and model_results.json written by analysis/clark_metrics.py
and prints (and writes to RESULTS.md in the same directory) the tables behind Table 4
(RMS ratio and NMSE of every model) and the Clark rows of Tables 3, 5 and 7, plus
self-consistency checks against the stored eval_results.npy. CPU only, seconds.

    .venv/bin/python analysis/clark_report.py [--dir analysis/results/clark]
"""
import argparse
import json
import os

import _common

parser = argparse.ArgumentParser(description='Markdown tables from the clark_metrics.py results.')
parser.add_argument('--dir', default=None, help='clark_metrics.py output directory (default: analysis/results/clark)')
D = parser.parse_args().dir or _common.results_dir('clark')
C = json.load(open(f'{D}/clark_results.json')); M = json.load(open(f'{D}/model_results.json'))
SETS = list(C)
# Clark correlations under the raw five-component metric, as computed by
# plots/compute_clark_correlations.py; used as a consistency check.
MAN = {'Re1000_nearwall_test': 0.491, 'Re1000_middle_test': 0.633, 'Re5200_nearwall': 0.480, 'Re5200_middle': 0.818}
L = []
L.append('# Clark baseline under the rotation-invariant metric + Table 3 aggregate rms/nmse\n')
L.append('Generated by `analysis/clark_metrics.py all` and `analysis/clark_report.py`.')
L.append('Raw numbers: `clark_results.{json,npy}`, `model_results.{json,npy}`.\n')
L.append('## Definitions\n')
L.append('- Clark: tau_hat = dev(g g^T)/12 applied to the raw stored normalized gradients (g = grad u / G), compared with raw stored targets (tau / (Delta^2 G^2)). Checked against `dataset_creation/sgs_filter_jhtb_data.py` lines 112-113: grad_normalized = grad/G, sgs_normalized = sgs/(delta^2 G^2), same local G (incl. +1e-8). So tau/(Delta^2 G^2) = (Delta^2/12) grad grad^T / (Delta^2 G^2) = g g^T/12 exactly; no standardization needed and amplitudes are absolute.')
L.append('- rho_raw: uncentered cosine over the raw 5 stored components, pooled over all points (the non-invariant metric, as in plots/compute_clark_correlations.py).')
L.append('- rho_inv: same on `deviatoric.to_orthonormal` coefficients (= eval_model `correlation`).')
L.append('- nmse = mean||p-t||^2 / mean||t||^2, rms_ratio = sqrt(mean||p||^2 / mean||t||^2), orthonormal basis, uncentered, pooled. Accumulated in float64.')
L.append('- Dissipation: verbatim logic of `analyze_dissipation.dissipation_stats` (wall units); mean_ratio = <eps_pred>/<eps_true>, std_ratio = std_pred/std_true.')
L.append('- Components: verbatim logic of `analyze_components.component_stats` (NB: its `rms_ratio` is a centered std ratio, unlike the aggregate one).')
L.append('- Trained models: `analyze_dissipation.predict` with training-set `scaling_factors` (computed before augmentation, as in NumpyTimeSeriesDataset), batch 25.\n')
L.append('## Self-consistency checks\n')
L.append('| set | raw-metric Clark (compute_clark_correlations.py) | rho_raw (this script) | pass |\n|---|---|---|---|')
for k, v in MAN.items():
    r = C[k]['rho_raw']; L.append(f'| {k} | {v:.3f} | {r:.4f} | {"PASS" if round(r,3)==v else "FAIL"} |')
cd = max(M[b][s]['corr_absdiff'] for b in M for s in SETS); nd = max(M[b][s]['nmse_absdiff'] for b in M for s in SETS)
md = max(abs(M[b][s]['target_second_moment_inv'] - M[b][s]['eval_target_second_moment']) / M[b][s]['eval_target_second_moment'] for b in M for s in SETS)
L.append(f'\nTrained models (64 run/set pairs): max |rho_inv - eval_results correlation| = {cd:.2e} (PASS, < 5e-5). '
         f'eval_results `loss` is F.mse_loss on orthonormal coefficients of unstandardized (raw stored scale) tensors, and `target_second_moment` is the per-coefficient mean of the same targets, so loss/target_second_moment is the same NMSE: max |nmse - loss/target_second_moment| = {nd:.2e} (PASS); max relative diff in target second moment = {md:.2e}.\n')
L.append('## Clark, aggregate (orthonormal basis unless noted)\n')
L.append('| set | rho_raw | rho_inv | nmse | rms_ratio |\n|---|---|---|---|---|')
for s in SETS:
    r = C[s]; L.append(f"| {s} | {r['rho_raw']:.4f} | {r['rho_inv']:.4f} | {r['nmse']:.4f} | {r['rms_ratio']:.4f} |")
L.append('\n## Clark, dissipation (wall units)\n')
L.append('| set | <eps+> true | <eps+> pred | mean_ratio | std true | std pred | std_ratio | rho_eps | backscatter true | backscatter pred |\n|---|---|---|---|---|---|---|---|---|---|')
for s in SETS:
    d = C[s]['dissipation']
    L.append(f"| {s} | {d['eps_true_mean']:.5f} | {d['eps_pred_mean']:.5f} | {d['mean_ratio']:.3f} | {d['eps_true_std']:.5f} | {d['eps_pred_std']:.5f} | {d['std_ratio']:.3f} | {d['eps_correlation']:.4f} | {100*d['backscatter_true']:.1f}% | {100*d['backscatter_pred']:.1f}% |")
L.append('\n## Clark, per-component (lab frame; corr / nmse / centered std ratio)\n')
comps = ['tau_11', 'tau_22', 'tau_33', 'tau_12', 'tau_13', 'tau_23']
L.append('| set | ' + ' | '.join(comps) + ' |\n|---|' + '---|' * 6)
for s in SETS:
    c = C[s]['components']
    L.append(f'| {s} | ' + ' | '.join(f"{c[k]['correlation']:.3f} / {c[k]['nmse']:.3f} / {c[k]['rms_ratio']:.3f}" for k in comps) + ' |')
L.append('\n## Trained Table 3 models: invariant rms_ratio / nmse\n')
short = {b: b.split('_', 4)[4].replace('_boxfilter_4x_sgs', '') for b in M}
L.append('| run | model | aug | ' + ' | '.join(SETS) + ' |\n|---|---|---|' + '---|' * len(SETS))
for b in M:
    m = M[b]
    L.append(f"| {short[b]} | {m['model_type']} | {m['train_aug_group']} | " + ' | '.join(f"{m[s]['rms_ratio']:.3f} / {m[s]['nmse']:.3f}" for s in SETS) + ' |')
L.append('\nrho_inv for reference (matches eval_results):\n')
L.append('| run | ' + ' | '.join(SETS) + ' |\n|---|' + '---|' * len(SETS))
for b in M:
    L.append(f'| {short[b]} | ' + ' | '.join(f"{M[b][s]['rho_inv']:.4f}" for s in SETS) + ' |')
open(f'{D}/RESULTS.md', 'w').write('\n'.join(L))
print('\n'.join(L))
